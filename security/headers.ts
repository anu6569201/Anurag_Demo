import fs from 'node:fs'
import path from 'node:path'

export const permissionsPolicy = [
  'accelerometer=()',
  'autoplay=()',
  'camera=()',
  'display-capture=()',
  'encrypted-media=()',
  'fullscreen=(self)',
  'geolocation=()',
  'gyroscope=()',
  'magnetometer=()',
  'microphone=()',
  'midi=()',
  'payment=()',
  'picture-in-picture=()',
  'publickey-credentials-get=()',
  'screen-wake-lock=()',
  'serial=()',
  'usb=()',
  'xr-spatial-tracking=()',
].join(', ')

/** Headers that are safe to send from the local HTTP dev and preview servers. */
export const localSecurityHeaders = {
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': permissionsPolicy,
  'X-DNS-Prefetch-Control': 'off',
  'X-Permitted-Cross-Domain-Policies': 'none',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'Origin-Agent-Cluster': '?1',
  'X-XSS-Protection': '0',
} as const

/**
 * Extra headers for a real HTTPS deployment.
 * HSTS is intentionally absent from local servers: sending it on http://127.0.0.1
 * can pin the browser to HTTPS and break later local sessions.
 */
export const productionOnlyHeaders = {
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains; preload',
  'Cross-Origin-Embedder-Policy': 'require-corp',
} as const

function productionHeaders(csp: string): Record<string, string> {
  return {
    ...localSecurityHeaders,
    ...productionOnlyHeaders,
    'Content-Security-Policy': csp,
  }
}

function cloudflareHeaders(headers: Record<string, string>, cacheControl: string): string {
  const lines = Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)
  lines.push(`  Cache-Control: ${cacheControl}`)
  return lines.join('\n')
}

function nginxHeaders(headers: Record<string, string>, cacheControl: string): string {
  const lines = Object.entries(headers).map(([name, value]) => {
    const escaped = value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')
    return `add_header ${name} "${escaped}" always;`
  })
  lines.push(`add_header Cache-Control "${cacheControl}" always;`)
  return lines.join('\n')
}

export function readIndexCsp(indexHtmlPath: string): string | undefined {
  const html = fs.readFileSync(indexHtmlPath, 'utf8')
  const match = /http-equiv="Content-Security-Policy" content="([^"]+)"/.exec(html)
  return match?.[1]
}

export function writeSecurityHeaders(outDir: string, csp: string): void {
  const headers = productionHeaders(csp)
  const documentCache = 'no-cache'
  const assetCache = 'public, max-age=31536000, immutable'
  fs.mkdirSync(outDir, { recursive: true })

  const cloudflare = [
    '/*',
    cloudflareHeaders(headers, documentCache),
    '',
    '/assets/*',
    cloudflareHeaders(headers, assetCache),
    '',
  ].join('\n')
  fs.writeFileSync(path.join(outDir, '_headers'), cloudflare)

  const nginx = [
    '# Generated by `vite build`. Include inside the HTTPS server that serves dist/.',
    '# Own every subdomain before submitting this host to the HSTS preload list.',
    'location / {',
    nginxHeaders(headers, documentCache)
      .split('\n')
      .map((line) => `  ${line}`)
      .join('\n'),
    '}',
    '',
    'location /assets/ {',
    nginxHeaders(headers, assetCache)
      .split('\n')
      .map((line) => `  ${line}`)
      .join('\n'),
    '}',
    '',
  ].join('\n')
  fs.writeFileSync(path.join(outDir, 'nginx-security-headers.conf'), nginx)

  const vercelHeaders = Object.entries(headers).map(([key, value]) => ({ key, value }))
  const vercel = {
    headers: [
      {
        source: '/(.*)',
        headers: [...vercelHeaders, { key: 'Cache-Control', value: documentCache }],
      },
      {
        source: '/assets/(.*)',
        headers: [...vercelHeaders, { key: 'Cache-Control', value: assetCache }],
      },
    ],
  }
  fs.writeFileSync(path.join(outDir, 'vercel.json'), `${JSON.stringify(vercel, null, 2)}\n`)
}
